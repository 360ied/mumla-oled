// Packet codec tests (step 5a.2): frame and parse both formats, byte-for-byte
// against fixtures generated by VoiceCodecFixtureGeneratorTest from the Java
// protobuf classes and PacketBuffer.

#include "VoiceCodec.h"
#include "TestHarness.h"

#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

namespace {

using mumla::voice_codec::ParsedDatagram;
using mumla::voice_codec::UdpFormat;

std::vector<uint8_t> readFixture(const std::string& name) {
    std::filesystem::path dir(MUMLA_VOICE_CODEC_FIXTURE_DIR);
    std::filesystem::path file = dir / name;
    std::ifstream in(file, std::ios::binary);
    if (!in.good()) {
        std::cerr << "  [FAIL] missing fixture " << file << std::endl;
        g_testFailures++;
        return {};
    }
    std::vector<uint8_t> data((std::istreambuf_iterator<char>(in)),
                              std::istreambuf_iterator<char>());
    if (data.empty()) {
        std::cerr << "  [FAIL] empty fixture " << file << std::endl;
        g_testFailures++;
    }
    return data;
}

mumla::audio::EncodedPacket makePacket(const uint8_t* opus,
                                       size_t len,
                                       uint64_t frameNumber,
                                       bool terminator) {
    mumla::audio::EncodedPacket packet;
    TEST_ASSERT_TRUE(len <= sizeof(packet.data));
    packet.size = len;
    if (len > 0 && opus != nullptr) {
        std::memcpy(packet.data, opus, len);
    }
    packet.frames = 0;
    packet.isTerminator = terminator;
    packet.frameNumber = frameNumber;
    return packet;
}

void checkBytes(const uint8_t* actual,
                size_t actualLen,
                const std::vector<uint8_t>& expected) {
    TEST_ASSERT_EQ(actualLen, expected.size());
    if (actualLen != expected.size()) return;
    for (size_t i = 0; i < expected.size(); ++i) {
        TEST_ASSERT_EQ(actual[i], expected[i]);
    }
}

}  // namespace

void run_voice_codec_tests() {
    g_testCount++;
    // Outbound framing byte-equality with the Java path.
    {
        const uint8_t opus[] = {0x01, 0x02, 0x03, 0x04};
        auto packet = makePacket(opus, sizeof(opus), 12345, false);
        uint8_t out[2048];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::LEGACY, packet, 0, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-legacy-voice-basic.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        uint8_t opus[100];
        for (int i = 0; i < 100; ++i) opus[i] = static_cast<uint8_t>(i);
        auto packet = makePacket(opus, sizeof(opus), 123456789, true);
        uint8_t out[2048];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::LEGACY, packet, 5, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-legacy-voice-whisper-terminator.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        auto packet = makePacket(nullptr, 0, 999, true);
        uint8_t out[2048];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::LEGACY, packet, 0, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-legacy-voice-empty-terminator.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        const uint8_t opus[] = {0x01, 0x02, 0x03, 0x04};
        auto packet = makePacket(opus, sizeof(opus), 12345, false);
        uint8_t out[4096];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::PROTOBUF, packet, 0, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-protobuf-voice-basic.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        uint8_t opus[100];
        for (int i = 0; i < 100; ++i) opus[i] = static_cast<uint8_t>(i);
        auto packet = makePacket(opus, sizeof(opus), 999, true);
        uint8_t out[4096];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::PROTOBUF, packet, 7, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-protobuf-voice-whisper-terminator.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        auto packet = makePacket(nullptr, 0, 999, true);
        uint8_t out[4096];
        size_t n = mumla::voice_codec::frameVoice(UdpFormat::PROTOBUF, packet, 0, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-protobuf-voice-empty-terminator.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        uint8_t out[32];
        size_t n = mumla::voice_codec::framePing(UdpFormat::LEGACY, 987654321, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-legacy-ping-basic.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }
    {
        uint8_t out[32];
        size_t n = mumla::voice_codec::framePing(UdpFormat::PROTOBUF, 987654321, out, sizeof(out));
        TEST_ASSERT_TRUE(n > 0);
        auto expected = readFixture("frame-protobuf-ping-basic.bin");
        if (!expected.empty()) checkBytes(out, n, expected);
    }

    // Inbound parsing (positional data and volume ignored, extended ping kept).
    {
        auto data = readFixture("parse-protobuf-voice-positional.bin");
        if (!data.empty()) {
            ParsedDatagram parsed;
            TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
                UdpFormat::PROTOBUF, data.data(), data.size(), 0, &parsed));
            TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::VOICE);
            TEST_ASSERT_EQ(parsed.session, 42);
            TEST_ASSERT_EQ(parsed.frameCount, static_cast<size_t>(1));
            TEST_ASSERT_EQ(parsed.frames[0].session, 42);
            TEST_ASSERT_EQ(parsed.frames[0].sequence, static_cast<uint32_t>(100));
            TEST_ASSERT_EQ(parsed.frames[0].flags, 2);
            TEST_ASSERT_EQ(parsed.frames[0].length, static_cast<uint16_t>(3));
            TEST_ASSERT_EQ(parsed.frames[0].data[0], 0x0A);
            TEST_ASSERT_EQ(parsed.frames[0].data[1], 0x0B);
            TEST_ASSERT_EQ(parsed.frames[0].data[2], 0x0C);
            TEST_ASSERT_TRUE(!parsed.frames[0].isTerminator);
            TEST_ASSERT_EQ(parsed.droppedFrames, static_cast<uint32_t>(0));
        }
    }
    {
        auto data = readFixture("parse-protobuf-ping-extended.bin");
        if (!data.empty()) {
            ParsedDatagram parsed;
            TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
                UdpFormat::PROTOBUF, data.data(), data.size(), 0, &parsed));
            TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::PING);
            TEST_ASSERT_EQ(parsed.pingTimestamp, static_cast<uint64_t>(987654321));
            TEST_ASSERT_EQ(parsed.serverVersionV2, static_cast<uint64_t>(0x0001000500010000ULL));
            TEST_ASSERT_EQ(parsed.maxBandwidthPerUser, static_cast<uint32_t>(128000));
        }
    }
    {
        auto data = readFixture("parse-legacy-voice-bundled-trailer.bin");
        if (!data.empty()) {
            ParsedDatagram parsed;
            TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
                UdpFormat::LEGACY, data.data(), data.size(), 0, &parsed));
            TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::VOICE);
            TEST_ASSERT_EQ(parsed.session, 42);
            TEST_ASSERT_EQ(parsed.frameCount, static_cast<size_t>(2));
            TEST_ASSERT_EQ(parsed.frames[0].session, 42);
            TEST_ASSERT_EQ(parsed.frames[0].sequence, static_cast<uint32_t>(100));
            TEST_ASSERT_EQ(parsed.frames[0].flags, 0);
            TEST_ASSERT_EQ(parsed.frames[0].length, static_cast<uint16_t>(4));
            TEST_ASSERT_TRUE(!parsed.frames[0].isTerminator);
            TEST_ASSERT_EQ(parsed.frames[1].session, 42);
            TEST_ASSERT_EQ(parsed.frames[1].sequence, static_cast<uint32_t>(101));
            TEST_ASSERT_EQ(parsed.frames[1].length, static_cast<uint16_t>(4));
            TEST_ASSERT_TRUE(parsed.frames[1].isTerminator);
            TEST_ASSERT_EQ(parsed.droppedFrames, static_cast<uint32_t>(0));
        }
    }
    {
        auto data = readFixture("parse-legacy-voice-empty-terminator.bin");
        if (!data.empty()) {
            ParsedDatagram parsed;
            TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
                UdpFormat::LEGACY, data.data(), data.size(), 0, &parsed));
            TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::VOICE);
            TEST_ASSERT_EQ(parsed.frameCount, static_cast<size_t>(1));
            TEST_ASSERT_EQ(parsed.frames[0].length, static_cast<uint16_t>(0));
            TEST_ASSERT_TRUE(parsed.frames[0].isTerminator);
        }
    }

    // Varint round-trip through legacy pings (PacketBuffer parity).
    {
        const int64_t stamps[] = {0, 42, 127, 128, 16383, 16384, 1000000,
                                  2097151, 2097152, 268435455, 268435456,
                                  2147483648LL, 4294967295LL, 4294967296LL,
                                  123456789012345LL, 0x7FFFFFFFFFFFFFFFL};
        for (int64_t stamp : stamps) {
            uint8_t out[16];
            size_t n = mumla::voice_codec::framePing(
                UdpFormat::LEGACY, static_cast<uint64_t>(stamp), out, sizeof(out));
            TEST_ASSERT_TRUE(n >= 2 && n <= 10);
            ParsedDatagram parsed;
            TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
                UdpFormat::LEGACY, out, n, 0, &parsed));
            TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::PING);
            TEST_ASSERT_EQ(parsed.pingTimestamp, static_cast<uint64_t>(stamp));
        }
    }

    // Unknown lead bytes and legacy non-voice types drop as UNKNOWN.
    {
        const uint8_t protobufUnknown[] = {0x02, 0x00};
        ParsedDatagram parsed;
        TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
            UdpFormat::PROTOBUF, protobufUnknown, sizeof(protobufUnknown), 0, &parsed));
        TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::UNKNOWN);
    }
    {
        const uint8_t legacyCeltAlpha[] = {0x00, 0x00};
        ParsedDatagram parsed;
        TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
            UdpFormat::LEGACY, legacyCeltAlpha, sizeof(legacyCeltAlpha), 0, &parsed));
        TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::UNKNOWN);
    }

    // Malformed input fails instead of producing audio.
    {
        const uint8_t truncated[] = {0x80};
        ParsedDatagram parsed;
        TEST_ASSERT_TRUE(!mumla::voice_codec::parseDatagram(
            UdpFormat::LEGACY, truncated, sizeof(truncated), 0, &parsed));
    }
    {
        const uint8_t badProtobuf[] = {0x00, 0xFF, 0xFF, 0xFF};
        ParsedDatagram parsed;
        TEST_ASSERT_TRUE(!mumla::voice_codec::parseDatagram(
            UdpFormat::PROTOBUF, badProtobuf, sizeof(badProtobuf), 0, &parsed));
    }

    // Twelve-frame bound: frames past the twelfth drop and count. Twenty
    // 4-byte frames keep the 12-byte positional-trailer check from tripping
    // (5-byte frames never land the remainder on exactly 12), so the bound
    // and the counter pin cleanly: 12 stored, 8 dropped.
    {
        uint8_t bundled[2048];
        bundled[0] = static_cast<uint8_t>((4 << 5) & 0xFF);
        size_t pos = 1;
        bundled[pos++] = 7;
        bundled[pos++] = 50;
        for (int i = 0; i < 20; ++i) {
            bundled[pos++] = 4;
            bundled[pos++] = static_cast<uint8_t>(0xA0 + (i & 0x0F));
            bundled[pos++] = static_cast<uint8_t>(0xB0 + (i & 0x0F));
            bundled[pos++] = static_cast<uint8_t>(0xC0 + (i & 0x0F));
            bundled[pos++] = static_cast<uint8_t>(0xD0 + (i & 0x0F));
        }
        ParsedDatagram parsed;
        TEST_ASSERT_TRUE(mumla::voice_codec::parseDatagram(
            UdpFormat::LEGACY, bundled, pos, 0, &parsed));
        TEST_ASSERT_TRUE(parsed.kind == ParsedDatagram::VOICE);
        TEST_ASSERT_EQ(parsed.frameCount, static_cast<size_t>(12));
        TEST_ASSERT_EQ(parsed.frames[11].sequence, static_cast<uint32_t>(61));
        TEST_ASSERT_EQ(parsed.droppedFrames, static_cast<uint32_t>(8));
    }
    std::cout << "  [PASS] voice codec (" << g_testFailures << " failures)" << std::endl;
}

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << " Mumla Voice Codec Tests" << std::endl;
    std::cout << "========================================" << std::endl;
    run_voice_codec_tests();
    std::cout << "========================================" << std::endl;
    if (g_testFailures == 0) {
        std::cout << " ALL VOICE CODEC TESTS PASSED!" << std::endl;
        return 0;
    }
    std::cerr << " FAILURE: " << g_testFailures << " test(s) failed!" << std::endl;
    return 1;
}
